#!/usr/bin/env node
/**
 * Generates `public/robots.txt` and `public/sitemap.xml` from the route
 * table and the SEO config.
 *
 * ## Why generated instead of hand-written
 *
 * The checklist asked for both files as static content. Hand-written, they
 * rot the moment someone adds a route: a new authenticated page is crawlable
 * until someone remembers to add a `Disallow`, and a new public page stays
 * invisible until someone remembers the sitemap. Both failures are silent.
 *
 * So this script *parses* `src/routes/index.tsx` and treats
 * `<ProtectedRoute>` as the definition of "must not be indexed". The route
 * table is already the source of truth for what is public, and it is the
 * file a developer necessarily edits when adding a page.
 *
 * It also fails loudly on the two drift cases that matter:
 *  - a page in `PUBLIC_PAGES` that the router does not serve (sitemap would
 *    advertise a 404 to Google),
 *  - a public route the router serves that is neither in `PUBLIC_PAGES` nor
 *    on the known-excluded list (a page that would be silently unindexed).
 *
 * Run as part of `npm run build`, before `vite build`, so `public/` is
 * copied into `dist/` with fresh files.
 */

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, "..");

const SITE_URL = "https://hispora.com.br";

// ---------------------------------------------------------------------------
// Read the shared page table. Same JSON the app imports, so there is exactly
// one place to edit when a public page is added.
// ---------------------------------------------------------------------------
const config = JSON.parse(
  readFileSync(resolve(root, "src/constants/public-pages.json"), "utf8"),
);
const pages = config.pages;
const INTENTIONALLY_UNLISTED = new Set(config.intentionallyUnlisted.paths);

if (!Array.isArray(pages) || pages.length === 0) {
  throw new Error("public-pages.json has no pages");
}

// ---------------------------------------------------------------------------
// Read the router and split routes into protected vs public.
// ---------------------------------------------------------------------------
const routesSrc = readFileSync(resolve(root, "src/routes/index.tsx"), "utf8");

function parseRoutes(src) {
  const protectedPaths = [];
  const publicPaths = [];
  const routeRe = /<Route\b([\s\S]*?)(?:\/>|<\/Route>)/g;
  for (const m of src.matchAll(routeRe)) {
    const block = m[1];
    const path = block.match(/path="([^"]+)"/)?.[1];
    if (!path || path === "*") continue;
    if (block.includes("ProtectedRoute")) protectedPaths.push(path);
    else publicPaths.push(path);
  }
  return { protectedPaths, publicPaths };
}

/** Collapse `/financial/revenue` → `/financial`, and drop `:params`, so the
 * robots rules stay short and still cover children. `Disallow: /financial`
 * is a prefix match, so it already covers every `/financial/*`. */
function toDisallowPrefixes(paths) {
  const prefixes = new Set();
  for (const p of paths) {
    const first = "/" + p.split("/").filter(Boolean)[0];
    prefixes.add(first);
  }
  return [...prefixes].sort();
}

const { protectedPaths, publicPaths } = parseRoutes(routesSrc);

// --- Drift checks ----------------------------------------------------------
const errors = [];

const routerPublic = new Set(publicPaths);
for (const page of pages) {
  for (const p of [page.path, ...(page.aliases ?? [])]) {
    if (!routerPublic.has(p)) {
      errors.push(
        `PUBLIC_PAGES lists "${p}" but the router does not serve it publicly. ` +
          `The sitemap would advertise a URL that 404s.`,
      );
    }
  }
}

const covered = new Set(
  pages.flatMap((p) => [p.path, ...(p.aliases ?? [])]),
);
for (const p of publicPaths) {
  if (!covered.has(p) && !INTENTIONALLY_UNLISTED.has(p)) {
    errors.push(
      `Route "${p}" is public but is neither in PUBLIC_PAGES nor in ` +
        `INTENTIONALLY_UNLISTED. Add it to one: a public page missing from ` +
        `the sitemap stays invisible to search, silently.`,
    );
  }
}

if (errors.length) {
  console.error("\nSEO config is out of sync with the router:\n");
  for (const e of errors) console.error("  • " + e);
  console.error("");
  process.exit(1);
}

// --- robots.txt ------------------------------------------------------------
// Token routes get their own, more explicit block further down, so they are
// filtered out here to avoid emitting the same prefix twice.
const TOKEN_PREFIXES = new Set(["/acesso-prontuario", "/assinatura-simulada"]);
const disallow = toDisallowPrefixes(protectedPaths).filter(
  (p) => !TOKEN_PREFIXES.has(p),
);

const robots = `# Generated by scripts/generate-seo-files.mjs — do not edit by hand.
# Derived from src/routes/index.tsx: every route behind <ProtectedRoute>
# is listed below automatically.

User-agent: *
Allow: /

# Authenticated application. Crawling these yields only the login redirect,
# wasting crawl budget on pages that can never be indexed usefully.
${disallow.map((p) => `Disallow: ${p}`).join("\n")}

# Auth screens: no content to rank for, and an indexed signup form competes
# with the landing page for the same queries.
Disallow: /login
Disallow: /signup
Disallow: /forgot-password
Disallow: /activate-account

# These URLs carry single-use access tokens. Disallow stops the fetch; the
# pages also send "noindex, nofollow", because a URL discovered through an
# inbound link can be indexed WITHOUT being fetched — robots.txt alone would
# not keep the token out of the index.
Disallow: /acesso-prontuario/
Disallow: /assinatura-simulada/

Sitemap: ${SITE_URL}/sitemap.xml
`;

writeFileSync(resolve(root, "public/robots.txt"), robots, "utf8");

// --- sitemap.xml -----------------------------------------------------------
// `lastmod` uses the build date. It is honest (the deployed document really
// did change) and avoids a hand-maintained date per URL going stale, which
// is worse than useless: Google learns to distrust the signal.
const lastmod = new Date().toISOString().slice(0, 10);

// Aliases are deliberately NOT listed. They exist so old links keep working,
// but each one declares `/termos` (etc.) as its canonical — listing them
// would ask Google to index URLs we just told it to ignore.
const urls = pages
  .map(
    (p) => `  <url>
    <loc>${p.path === "/" ? SITE_URL + "/" : SITE_URL + p.path}</loc>
    <lastmod>${lastmod}</lastmod>
    <changefreq>${p.changefreq}</changefreq>
    <priority>${p.priority.toFixed(1)}</priority>
  </url>`,
  )
  .join("\n");

const sitemap = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by scripts/generate-seo-files.mjs — do not edit by hand. -->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls}
</urlset>
`;

writeFileSync(resolve(root, "public/sitemap.xml"), sitemap, "utf8");

const aliasCount = pages.reduce((n, p) => n + (p.aliases?.length ?? 0), 0);
console.log(
  `SEO files generated: ${pages.length} sitemap URLs ` +
    `(+${aliasCount} aliases canonicalised, not listed), ` +
    `${disallow.length + 6} robots Disallow rules.`,
);
