/** The document structure the backend renders the PDF from — returned by
 * `GET /reports/:id/preview` so the on-screen preview matches the PDF
 * instead of being rebuilt (and drifting) on the frontend. */
export interface DocumentSpec {
  documentType: "prescription" | "report" | "exam";
  title: string;
  doctor: { name: string; crm: string; specialty?: string | null };
  patient: {
    name: string;
    cpf?: string | null;
    birthDate?: string | null;
    gender?: string | null;
  };
  issueDate: string;
  sections: Array<
    | {
        kind: "key-values";
        heading?: string;
        items: Array<{ label: string; value: string }>;
      }
    | { kind: "rich-text"; heading: string; content: RichTextDoc | null }
    | { kind: "plain-text"; heading?: string; text: string }
  >;
  signatureStatus: SignatureStatus;
}

export interface ReportFilters {
  patientId?: string;
  status?: DocumentStatus;
  startDate?: string;
  endDate?: string;
  search?: string;
}

export const reportsApi = {
  list: (filters: ReportFilters = {}): Promise<Report[]> => {
    const params = new URLSearchParams();
    for (const [key, value] of Object.entries(filters)) {
      if (value) params.set(key, value);
    }
    const qs = params.toString();
    return api(`/reports${qs ? `?${qs}` : ""}`);
  },

  getById: (id: string): Promise<Report> => api(`/reports/${id}`),

  create: (data: ReportPayload): Promise<Report> =>
    api("/reports", { method: "POST", body: data }),

  update: (id: string, data: Partial<ReportPayload>): Promise<Report> =>
    api(`/reports/${id}`, { method: "PATCH", body: data }),

  remove: (id: string): Promise<{ message: string }> =>
    api(`/reports/${id}`, { method: "DELETE" }),

  cancel: (id: string): Promise<Report> =>
    api(`/reports/${id}/cancel`, { method: "POST" }),

  /** Uploads a pre-existing laudo document. Separate from `create`/`update`
   * because the clinical fields are rich-text objects that wouldn't survive
   * a multipart round-trip. */
  attachFile: (id: string, file: File): Promise<Report> => {
    const formData = new FormData();
    formData.append("file", file);
    return api(`/reports/${id}/file`, {
      method: "POST",
      body: formData,
      isFormData: true,
    });
  },

  removeFile: (id: string): Promise<Report> =>
    api(`/reports/${id}/file`, { method: "DELETE" }),

  /** Laudos filed under a patient's medical record — mirrors how the other
   * record tabs (atestados, exames) load their data. */
  listForPatient: (patientId: string): Promise<Report[]> =>
    api(`/patients/${patientId}/reports`),

  preview: (id: string): Promise<DocumentSpec> => api(`/reports/${id}/preview`),

  generatePdf: (id: string): Promise<Report> =>
    api(`/reports/${id}/generate-pdf`, { method: "POST" }),

  /** "Enviar sem assinatura digital" — delivers the already-generated PDF
   * to the patient as-is. */
  send: (id: string): Promise<Report> =>
    api(`/reports/${id}/send`, { method: "POST" }),

  /** "Assinar digitalmente e enviar", step 1 — starts the (simulated)
   * signature request and returns the URL to open in a new tab. */
  requestSignature: (
    id: string,
  ): Promise<{ report: Report; signingUrl: string }> =>
    api(`/reports/${id}/request-signature`, { method: "POST" }),

  /** Step 2, called from the signature-simulator page once "signed". */
  confirmSignature: (id: string, externalSignatureId: string): Promise<Report> =>
    api(`/reports/${id}/confirm-signature`, {
      method: "POST",
      body: { externalSignatureId },
    }),
};
