import { api } from "./api";

/** Mirrors the backend `ReportType` enum (`report.entity.ts`) — same values,
 * same order. The "Outro" option requires `reportTypeOther`. */
export const REPORT_TYPES = [
  { value: "laudo_medico", label: "Laudo médico" },
  { value: "laudo_exame", label: "Laudo de exame" },
  { value: "relatorio_medico", label: "Relatório médico" },
  { value: "relatorio_acompanhamento", label: "Relatório de acompanhamento" },
  { value: "laudo_administrativo", label: "Laudo para fins administrativos" },
  { value: "laudo_trabalhista", label: "Laudo para fins trabalhistas" },
  { value: "laudo_previdenciario", label: "Laudo para fins previdenciários" },
  { value: "outro", label: "Outro" },
] as const;

export type ReportType = (typeof REPORT_TYPES)[number]["value"];

export function reportTypeLabel(
  type: ReportType | string,
  other?: string | null,
): string {
  if (type === "outro") return other?.trim() || "Outro";
  return REPORT_TYPES.find((t) => t.value === type)?.label || type;
}

/** Document lifecycle, mirroring the backend `DocumentStatus`. `signed` is
 * only ever set by a real signature provider — none exists yet, so nothing
 * in the UI should present a document as digitally signed on its own. */
export type DocumentStatus =
  | "draft"
  | "generated"
  | "sent"
  | "signed"
  | "canceled";

export type SignatureStatus =
  | "none"
  | "pending"
  | "signed"
  | "failed"
  | "rejected";

export const REPORT_STATUS_LABELS: Record<DocumentStatus, string> = {
  draft: "Rascunho",
  generated: "Gerado",
  sent: "Enviado",
  signed: "Assinado",
  canceled: "Cancelado",
};

/** Tiptap/ProseMirror JSON. Opaque here — the editor produces it and the
 * backend's `prosemirror-to-pdfkit` renderer consumes it. */
export type RichTextDoc = {
  type: string;
  content?: unknown[];
  [key: string]: unknown;
};

